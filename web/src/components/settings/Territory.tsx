/** How much of a surface is held, as one mark down the three columns: a full
 *  dot = held, half = partly, a ring = open; nothing to hold draws nothing
 *  (its words say so). The words beside it carry the fact — the mark only
 *  lets the eye run down a column. */
function HoldMark({ hold }: { hold: Hold }) {
  const base = 'inline-block h-[7px] w-[7px] shrink-0 rounded-full'
  if (hold === 'held') return <span aria-hidden="true" className={`${base} bg-ink`} />
  if (hold === 'partial')
    return (
      <span aria-hidden="true" className={`${base} border border-ink`} style={{ background: 'linear-gradient(to right, var(--ink) 50%, transparent 50%)' }} />
    )
  if (hold === 'open') return <span aria-hidden="true" className={`${base} border border-ink-3`} />
  return <span aria-hidden="true" className="inline-block w-[7px] shrink-0 max-sm:hidden" />
}

