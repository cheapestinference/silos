// The fence is rolled out one agent at a time (each one
// confirmed by the owner): `enabled` lists the agents whose files are fenced. A server
// with no territory route says so in one line (the tab is its only house).
export function TerritorySection() {
  const agents = useStore((s) => s.agents)
  const [saved, setSaved] = useState<string[] | null | undefined>(undefined)
  const [draft, setDraft] = useState('')
  const [status, setStatus] = useState<'idle' | 'saving' | 'saved'>('idle')
  const [error, setError] = useState<string | null>(null)
  // null until the server has said the gate: no toggles yet.
  const [enabled, setEnabled] = useState<string[] | null>(null)
  const [gateError, setGateError] = useState<string | null>(null)
  // per agent: its harness and what the fence covers there (server facts)
  const [fenceFacts, setFenceFacts] = useState<Map<string, TerritoryAgent>>(new Map())
  // the other two surfaces: null = not (yet) known — the cell stays quiet
  const [vault, setVault] = useState<VaultEntry[] | null>(null)
  const [egress, setEgress] = useState<Map<string, AgentEgress> | null>(null)
  const [refusals, setRefusals] = useState<EgressRejection[]>([])
  const [openId, setOpenId] = useState<string | null>(null)
  const descriptors = useHarnessDescriptors()

  useEffect(() => {
    let cancelled = false
    Promise.resolve(api.territory.get())
      .then((v) => {
        if (cancelled) return
        if (!v || !Array.isArray(v.privatePaths)) {
          setSaved(null)
          return
        }
        setSaved(v.privatePaths)
        setDraft(v.privatePaths.join('\n'))
        setEnabled(Array.isArray(v.enabled) ? v.enabled : null)
        setFenceFacts(new Map((Array.isArray(v.agents) ? v.agents : []).map((a) => [a.id, a])))
      })
      .catch(() => {
        if (!cancelled) setSaved(null)
      })
    Promise.resolve(api.vault.list())
      .then((v) => {
        if (!cancelled && Array.isArray(v)) setVault(v)
      })
      .catch(() => {
        /* the secrets cells stay quiet */
      })
    Promise.resolve(api.territory.egress())
      .then((v) => {
        if (!cancelled && v && Array.isArray(v.agents)) setEgress(new Map(v.agents.map((a) => [a.id, a])))
      })
      .catch(() => {
        /* an older server: no network surface yet */
      })
    Promise.resolve(api.territory.egressRejections({ limit: 500 }))
      .then((r) => {
        if (!cancelled && Array.isArray(r)) setRefusals(r)
      })
      .catch(() => {
        /* owner-only rows; none to count */
      })
    return () => {
      cancelled = true
    }
  }, [])

  const roster = useMemo(() => agents.filter((a) => a.id !== MASTER_ID && !a.archived), [agents])
  const today = useMemo(() => refusedToday(refusals), [refusals])
  if (saved === null) {
    return (
      <Section title="Territory">
        <p data-testid="territory-absent">This Silos server doesn’t fence agents yet — restart it after updating.</p>
      </Section>
    )
  }
  const lines = draft
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l !== '')
  const dirty = saved !== undefined && lines.join('\n') !== saved.join('\n')
  const nameOf = (id: string | null): string => (id === null ? 'you' : (agents.find((a) => a.id === id)?.name ?? id))

  // An engine whose fence denies kinds there (ui.territoryFenced) says what it
  // covers; Claude Code's row stays as it always was.
  const otherHarness = (id: string): TerritoryAgent | null => {
    const h = fenceFacts.get(id)
    return h && descriptorIn(descriptors, h.harness).ui.territoryFenced && h.fenced.length > 0 ? h : null
  }
  // configured private paths an agent is NOT kept out of (it works inside or
  // around one) — the only per-agent private-path news
  const privateExceptions = (scope: FenceScope): string[] => {
    const kept = new Set(scope.blocked.filter((b) => b.kind === 'private').flatMap((b) => b.paths))
    return (saved ?? []).map((p) => p.replace(/\/+$/, '')).filter((p) => !kept.has(p))
  }
  // the extra sentence of each engine present (ui.territoryNote), once each, in agent order
  const notes = [
    ...new Set(
      roster.flatMap((a) => {
        const h = fenceFacts.get(a.id)
        const note = h ? descriptorIn(descriptors, h.harness).ui.territoryNote : null
        return note ? [note] : []
      }),
    ),
  ]
  const engineLabelOf = (a: AgentView): string => fenceFacts.get(a.id)?.label ?? (a.framework ? descriptorIn(descriptors, a.framework).label : 'its engine')

  async function toggleFence(id: string): Promise<void> {
    if (enabled === null) return
    const next = enabled.includes(id) ? enabled.filter((x) => x !== id) : [...enabled, id]
    setGateError(null)
    try {
      const r = await api.territory.setEnabled(next)
      setEnabled(Array.isArray(r.enabled) ? r.enabled : next)
    } catch (err) {
      setGateError(err instanceof Error ? err.message : String(err))
    }
  }

  async function save(): Promise<void> {
    setStatus('saving')
    setError(null)
    try {
      const r = await api.territory.set(lines)
      setSaved(r.privatePaths)
      setDraft(r.privatePaths.join('\n'))
      setStatus('saved')
    } catch (err) {
      setError(err instanceof Error ? err.message : String(err))
      setStatus('idle')
    }
  }

  // one row per agent at every width; a phone keeps three narrow columns for
  // the marks alone
  const ROW_GRID =
    'grid grid-cols-[minmax(0,1fr)_2.75rem_3.25rem_3.5rem] items-center gap-x-2 sm:grid-cols-[minmax(0,1fr)_7.5rem_8rem_8.5rem] sm:gap-x-3 sm:gap-y-2'
  return (
    <Section
      title="Territory"
      description="What holds each agent, surface by surface: the files it can touch, the secrets it can use, the hosts it can call. Each surface says what holds it — and what doesn't."
    >
      {saved === undefined ? (
        <p>Loading…</p>
      ) : (
        <>
          {roster.length > 0 ? (
            <div data-testid="territory-roster">
              <div className={`${ROW_GRID} hidden pb-1.5 text-[11px] text-ink-3 sm:grid`}>
                <span>Agent</span>
                <span>Files</span>
                <span>Secrets</span>
                <span>Network</span>
              </div>
              <div className={`${ROW_GRID} pb-1.5 text-center text-[11px] text-ink-3 sm:hidden`} aria-hidden="true">
                <span />
                <span>Files</span>
                <span>Secrets</span>
                <span>Network</span>
              </div>
              <ul className="border-t border-line">
                {roster.map((a) => {
                  const on = enabled?.includes(a.id) ?? false
                  const facts = fenceFacts.get(a.id)
                  const other = otherHarness(a.id)
                  const secrets = vault ? secretsOf(vault, a.id, a.folder) : null
                  const eg = egress?.get(a.id)
                  const refused = today.get(a.id) ?? 0
                  const isOpen = openId === a.id
                  return (
                    <li key={a.id} className="border-b border-line">
                      <div className={`${ROW_GRID} py-2.5`}>
                        <div className="min-w-0">
                          <button
                            type="button"
                            aria-expanded={isOpen}
                            onClick={() => setOpenId(isOpen ? null : a.id)}
                            className="flex w-full min-w-0 items-center gap-1.5 text-left text-[13px] text-ink hover:text-terracotta"
                          >
                            <ChevronRight
                              size={13}
                              aria-hidden="true"
                              className={`shrink-0 text-ink-3 transition-transform duration-150 ${isOpen ? 'rotate-90' : ''}`}
                            />
                            <span className="truncate">
                              {a.emoji ? `${a.emoji} ` : ''}
                              {a.name}
                            </span>
                          </button>
                          {/* on a phone the refusals ride under the name — the Network cell is a dot alone */}
                          {refused > 0 ? (
                            <span
                              className="block pl-[19px] text-[11px] text-[var(--health-amber)] sm:hidden"
                              aria-hidden="true"
                              data-testid={`refused-phone-${a.id}`}
                            >
                              {refused} refused today
                            </span>
                          ) : null}
                        </div>
                        <div className="contents">
                          <Cell label="Files">
                            {a.folder == null ? (
                              <>
                                <HoldMark hold="none" />
                                <PhoneDash />
                                <span className={`text-ink-3 ${WORDS}`}>no folder</span>
                              </>
                            ) : enabled !== null ? (
                              <FenceSwitch id={a.id} name={a.name} on={on} onToggle={() => void toggleFence(a.id)} />
                            ) : null}
                          </Cell>
                          <Cell label="Secrets">
                            {secrets ? (
                              <>
                                <HoldMark hold={secrets.hold} />
                                {secrets.hold === 'none' ? <PhoneDash /> : null}
                                <span className={`${WORDS} ${secrets.hold === 'none' ? 'text-ink-3' : 'text-ink'}`}>{secretsWords(secrets)}</span>
                              </>
                            ) : null}
                          </Cell>
                          <Cell label="Network">
                            {eg ? (
                              <>
                                <HoldMark hold={eg.mode === 'allowlist' ? 'held' : 'open'} />
                                <span className={`min-w-0 ${WORDS}`}>
                                  <span className={eg.mode === 'allowlist' ? 'text-ink' : 'text-ink-2'}>
                                    {eg.mode === 'allowlist' ? (eg.hosts.length === 0 ? 'allowlist, engine only' : `allowlist of ${eg.hosts.length}`) : 'open'}
                                  </span>
                                  {refused > 0 ? (
                                    <span className="block text-[11px] text-[var(--health-amber)]" data-testid={`refused-${a.id}`}>
                                      {refused} refused today
                                    </span>
                                  ) : null}
                                </span>
                              </>
                            ) : null}
                          </Cell>
                        </div>
                      </div>
                      {isOpen ? (
                        <div className="mb-3 rounded-md bg-panel/60 px-3 sm:ml-5" data-testid={`territory-agent-${a.id}`}>
                          <Band name="Files">
                            {a.folder == null ? (
                              <p>No folder — nothing on disk to fence.</p>
                            ) : (
                              <>
                                {facts?.scope ? (
                                  <FenceScopeLines
                                    scope={facts.scope}
                                    on={on}
                                    kept={false}
                                    preview
                                    privateExceptions={on ? privateExceptions(facts.scope) : []}
                                  />
                                ) : (
                                  <span className="font-mono">{a.folder}</span>
                                )}
                                {other ? (
                                  <span data-testid={`fence-harness-${a.id}`} className="mt-1 block">
                                    on {other.label}: {other.fenced.join(' · ')} kept out
                                  </span>
                                ) : null}
                              </>
                            )}
                          </Band>
                          <Band name="Secrets">
                            {secrets ? <SecretsBand agent={a} secrets={secrets} nameOf={nameOf} /> : <p>The Vault could not be read.</p>}
                          </Band>
                          <Band name="Network">
                            {eg ? (
                              <NetworkBand
                                agent={a}
                                egress={eg}
                                engineLabel={engineLabelOf(a)}
                                secrets={secrets ?? { signed: [], delivered: [], hold: 'none' }}
                                onChange={(next) => setEgress((m) => new Map(m ?? []).set(next.id, next))}
                              />
                            ) : (
                              <p>This server does not run the egress proxy yet.</p>
                            )}
                          </Band>
                        </div>
                      ) : null}
                    </li>
                  )
                })}
              </ul>
              {gateError ? <p className="mt-2 font-mono text-[11px] text-terracotta">{gateError}</p> : null}
              <p className="mt-2 text-[11px] leading-relaxed text-ink-3">
                A new agent is born fenced. While its files are open it stays on «Only when told». Every agent meets the API as itself, with its own token.
              </p>
            </div>
          ) : null}

          <div className="mt-8">
            <Surfaces engineNotes={notes} />
          </div>

          <div className="mt-6">
            <label htmlFor="territory-private" className="text-sm text-ink">
              Private paths{' '}
              <span className="text-ink-2">
                — every fenced agent is kept out of them (one per line; <span className="font-mono">~</span> allowed)
              </span>
            </label>
            <textarea
              id="territory-private"
              value={draft}
              onChange={(e) => {
                setDraft(e.target.value)
                setStatus('idle')
              }}
              rows={Math.min(10, Math.max(3, draft.split('\n').length + 1))}
              spellCheck={false}
              className="mt-2 w-full resize-y rounded-md border border-line bg-panel px-2.5 py-2 font-mono text-xs leading-relaxed text-ink"
            />
            <div className="mt-2 flex items-center gap-3">
              <button type="button" onClick={() => void save()} disabled={status === 'saving' || !dirty} aria-label="Save private paths" className={QUIET_BTN}>
                {status === 'saving' ? 'Saving…' : 'Save'}
              </button>
              {status === 'saved' && !dirty ? <span className="text-xs text-ink-2">Saved.</span> : null}
              <span className="text-[11px] text-ink-3">A running console picks a change up when it restarts.</span>
            </div>
            {error ? <p className="mt-2 font-mono text-[11px] text-terracotta">{error}</p> : null}
          </div>
        </>
      )}
    </Section>
  )
}
