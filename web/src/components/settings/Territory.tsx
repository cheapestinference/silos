/** The proxy's refusals for one agent, folded like the signed calls. */
function RefusalsFold({ agentId, refreshKey }: { agentId: string; refreshKey: unknown }) {
  const [rows, setRows] = useState<EgressRejection[] | null>(null)
  const [open, setOpen] = useState(false)
  useEffect(() => {
    let cancelled = false
    Promise.resolve(api.territory.egressRejections({ agent: agentId, limit: 20 }))
      .then((r) => {
        if (!cancelled) setRows(r ?? [])
      })
      .catch(() => {
        if (!cancelled) setRows([])
      })
    return () => {
      cancelled = true
    }
  }, [agentId, refreshKey])
  if (rows === null) return null
  if (rows.length === 0)
    return (
      <p className="text-[11px] text-ink-3" data-testid="egress-refusals">
        No refused calls yet — each one will show here.
      </p>
    )
  const last = rows[0]!
  const summary = `${rows.length === 20 ? 'Last 20' : rows.length} refused · last ${relTimeOf(last.at) ?? ''} — ${last.host}`
  return (
    <div data-testid="egress-refusals">
      <button
        type="button"
        aria-expanded={open}
        onClick={() => setOpen((v) => !v)}
        className="flex min-w-0 items-center gap-1 text-left text-[11px] text-[var(--health-amber)] hover:text-ink"
      >
        <ChevronRight size={12} aria-hidden="true" className={`shrink-0 transition-transform duration-150 ${open ? 'rotate-90' : ''}`} />
        <span className="truncate">{summary}</span>
      </button>
      {open ? (
        <ul className="mt-1.5 divide-y divide-line/50 font-mono text-[10.5px]">
          {rows.map((r, i) => (
            <li
              key={`${r.at}-${i}`}
              className="grid grid-cols-[minmax(0,1fr)_minmax(0,1.3fr)_3.6rem] items-baseline gap-x-2 py-1 max-sm:grid-cols-[minmax(0,1fr)_3.6rem] max-sm:gap-y-0.5"
            >
              <span className="truncate text-ink" title={`${r.host}:${r.port}`}>
                {r.host}
                {r.port !== 443 ? <span className="text-ink-3">:{r.port}</span> : null}
              </span>
              <span className="truncate font-sans text-[11px] text-ink-2 max-sm:order-3 max-sm:col-span-2" title={r.reason}>
                {r.reason}
              </span>
              <span className="whitespace-nowrap text-right text-ink-3">{relTimeOf(r.at)}</span>
            </li>
          ))}
        </ul>
      ) : null}
    </div>
  )
}

function NetworkBand({
  agent,
  egress,
  engineLabel,
  secrets,
  onChange,
}: {
  agent: AgentView
  egress: AgentEgress
  engineLabel: string
  secrets: SecretsReading
  onChange: (next: AgentEgress) => void
}) {
  const [draft, setDraft] = useState('')
  const [busy, setBusy] = useState(false)
  const [refusal, setRefusal] = useState<string | null>(null)
  const [engineOpen, setEngineOpen] = useState(false)
  const allow = egress.mode === 'allowlist'
  const pinned = (egress.engine?.hosts ?? []).filter((h) => !h.optional)
  const offered = (egress.engine?.hosts ?? []).filter((h) => h.optional && !egress.hosts.includes(h.host))
  const served = servedNotCallable(secrets, egress)

  async function save(change: { mode?: AgentEgress['mode']; hosts?: string[] }): Promise<boolean> {
    setBusy(true)
    try {
      onChange(await api.territory.setEgress(agent.id, change))
      setRefusal(null)
      return true
    } catch (e) {
      setRefusal(e instanceof Error ? e.message : String(e))
      return false
    } finally {
      setBusy(false)
    }
  }
  async function add(): Promise<void> {
    const hosts = draft
      .split(/[\s,]+/)
      .map((h) => h.trim())
      .filter(Boolean)
    if (hosts.length === 0 || busy) return
    if (await save({ hosts: [...egress.hosts, ...hosts] })) setDraft('')
  }

  const seg = (on: boolean): string => `px-2.5 py-1 text-[11.5px] transition-colors duration-150 ${on ? 'bg-ink text-canvas' : 'text-ink-2 hover:text-ink'}`
  return (
    <div className="space-y-2" data-testid={`network-${agent.id}`}>
      <div className="flex flex-wrap items-center gap-x-3 gap-y-1">
        <div role="radiogroup" aria-label={`Network: ${agent.name}`} className="inline-flex overflow-hidden rounded-md border border-line">
          <button
            type="button"
            role="radio"
            aria-checked={!allow}
            disabled={busy}
            onClick={() => {
              if (allow) void save({ mode: 'open' })
            }}
            className={seg(!allow)}
          >
            Open
          </button>
          <button
            type="button"
            role="radio"
            aria-checked={allow}
            disabled={busy}
            onClick={() => {
              if (!allow) void save({ mode: 'allowlist' })
            }}
            className={`border-l border-line ${seg(allow)}`}
          >
            Allowlist
          </button>
        </div>
        <span>{allow ? `only the hosts below, plus ${engineLabel}'s own` : 'it can call any host'}</span>
      </div>
      {allow ? (
        <>
          <ul className="flex flex-wrap gap-1.5" aria-label={`${agent.name}'s allowlist`}>
            {egress.hosts.map((h) => (
              <li key={h} className="inline-flex items-center gap-1 rounded-md border border-line bg-panel py-0.5 pl-2 pr-1 font-mono text-[11px] text-ink">
                {h}
                <button
                  type="button"
                  aria-label={`Remove ${h}`}
                  disabled={busy}
                  onClick={() => void save({ hosts: egress.hosts.filter((x) => x !== h) })}
                  className="rounded p-0.5 text-ink-3 hover:text-terracotta"
                >
                  <X size={11} aria-hidden="true" />
                </button>
              </li>
            ))}
            <li className="inline-flex">
              <form
                className="inline-flex"
                onSubmit={(ev) => {
                  ev.preventDefault()
                  void add()
                }}
              >
                <input
                  aria-label={`Add a host for ${agent.name}`}
                  value={draft}
                  onChange={(e) => setDraft(e.target.value)}
                  placeholder={egress.hosts.length === 0 ? 'api.example.com or *.example.com' : 'add a host'}
                  spellCheck={false}
                  className="w-52 max-w-full rounded-l-md border border-line bg-canvas px-2 py-0.5 font-mono text-[11px] text-ink outline-none focus:border-terracotta"
                />
                <button
                  type="submit"
                  disabled={busy || draft.trim() === ''}
                  className="rounded-r-md border border-l-0 border-line px-2 text-[11px] text-ink-2 hover:text-ink disabled:opacity-40"
                >
                  Add
                </button>
              </form>
            </li>
          </ul>
          {refusal ? (
            <p role="alert" className="text-[11px] leading-snug text-terracotta">
              {refusal}
            </p>
          ) : null}
          {egress.engine ? (
            <div>
              <button
                type="button"
                aria-expanded={engineOpen}
                onClick={() => setEngineOpen((v) => !v)}
                className="flex items-center gap-1 text-[11px] text-ink-2 hover:text-ink"
              >
                <ChevronRight size={12} aria-hidden="true" className={`shrink-0 transition-transform duration-150 ${engineOpen ? 'rotate-90' : ''}`} />
                {engineLabel}'s own: {plural(pinned.length, 'host')}, always let through
              </button>
              {engineOpen ? (
                <div className="mt-1.5 pl-4">
                  <ul className="grid grid-cols-1 gap-x-4 gap-y-0.5 sm:grid-cols-2">
                    {pinned.map((h) => (
                      <li key={h.host} className="min-w-0 truncate text-[11px]" title={h.reason}>
                        <span className="font-mono text-ink">{h.host}</span> <span className="text-ink-3">{h.reason}</span>
                      </li>
                    ))}
                  </ul>
                  <p className="mt-1 text-[10.5px] text-ink-3">
                    From{' '}
                    <a href={egress.engine.source} target="_blank" rel="noreferrer" className="underline-offset-2 hover:underline">
                      {egress.engine.source.replace(/^https?:\/\//, '')}
                    </a>
                  </p>
                </div>
              ) : null}
              {offered.length > 0 ? (
                <div className="mt-1.5 flex flex-wrap items-center gap-1.5 pl-4">
                  <span className="text-[11px] text-ink-3">Optional for {engineLabel}:</span>
                  {offered.map((h) => (
                    <button
                      key={h.host}
                      type="button"
                      disabled={busy}
                      title={h.reason}
                      aria-label={`Allow ${h.host} (${h.reason})`}
                      onClick={() => void save({ hosts: [...egress.hosts, h.host] })}
                      className="inline-flex items-center gap-0.5 rounded-md border border-dashed border-line px-1.5 py-0.5 font-mono text-[10.5px] text-ink-2 hover:border-ink-2 hover:text-ink"
                    >
                      <Plus size={10} aria-hidden="true" />
                      {h.host}
                    </button>
                  ))}
                </div>
              ) : null}
            </div>
          ) : (
            <p className="text-[11px] text-ink-3">Its engine documents no hosts of its own — only the ones above get through.</p>
          )}
          {served.length > 0 ? (
            <p className="text-[12px] text-ink" data-testid={`together-${agent.id}`}>
              It works with{' '}
              {served.map((s, i) => (
                <span key={s.name}>
                  {i > 0 ? (i === served.length - 1 ? ' and ' : ', ') : ''}
                  <span className="font-mono text-[11px]">{s.host}</span>
                </span>
              ))}{' '}
              through its signed {served.length === 1 ? 'entry' : 'entries'} without being able to call {served.length === 1 ? 'it' : 'them'} — the call leaves
              the server.
            </p>
          ) : null}
          <p className="text-[11px] text-ink-3">A running console picks a change up when it restarts.</p>
        </>
      ) : refusal ? (
        <p role="alert" className="text-[11px] leading-snug text-terracotta">
          {refusal}
        </p>
      ) : null}
      <RefusalsFold agentId={agent.id} refreshKey={egress.mode} />
    </div>
  )
}

