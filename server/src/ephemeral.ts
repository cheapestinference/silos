import { tmpdir } from 'node:os'
import { mungePath } from './agent-registry.js'

// Ephemeral-noise rule. Every problem is solved at the system level so that
// no other platform user ever suffers it — not by hand-cleaning the owner's
// data. The concrete problem class: sessions whose cwd hangs off the OS
// tmpdir (smoke tests, session scratchpads, bug repros — e.g.
// "-tmp-claude-1234--home-u-...-scratchpad-r1") are internal noise from
// Claude Code/Silos itself, never real owner work, and clutter the
// Master agent as untitled orphans.
//
// Why derive from os.tmpdir() and NOT hardcode "/tmp": the server can run
// on any platform Node supports — macOS resolves tmpdir to
// /var/folders/xx/yyyy/T, and any environment can override TMPDIR/TMP/TEMP.
// os.tmpdir() is already Node's source of truth for "where THIS process's
// tmp lands" (it respects those env vars with the right per-platform
// fallback); hardcoding "/tmp" would work today on Linux but silently fail
// on any other machine. Deriving it is the only way for the rule to be
// correct everywhere with zero maintenance.
//
// Empirically verified in this environment: with no TMPDIR set,
// os.tmpdir() returns exactly "/tmp" — mungePath('/tmp') = '-tmp', which IS
// a prefix of the owner's real noise folders
// ("-tmp-claude-1234--home-u-...-scratchpad-r1"). No fallback to a
// fixed "/tmp" is needed alongside os.tmpdir(): in this process they already
// coincide. Documented here in case they ever stop coinciding (see the
// limitation below) so it's clear this was a verified decision, not an
// oversight.
//
// Accepted limitation: if a session was recorded under a different tmpdir
// than the one the process sees NOW (e.g. TMPDIR changed between startups,
// or the JSONL was copied from another machine/container), that folder
// won't match and won't be hidden. Acceptable: the rule protects the OS
// tmpdir as seen by the server that's currently running, which is exactly
// the real case (noise generated by the session in progress on this
// machine).

// Munges an arbitrary tmpdir into the folder shape it would have under
// ~/.claude/projects — kept separate from ephemeralPrefix() so the
// derivation can be tested in isolation with fake tmpdirs, without
// depending on the real os.tmpdir().
export function mungeTmpdir(tmpdirPath: string): string {
  return mungePath(tmpdirPath)
}

// Munged prefix of this process's real tmpdir — computed once at startup
// (see index.ts) and reused for the whole run; os.tmpdir() doesn't change
// at runtime within a single process.
export function ephemeralPrefix(): string {
  return mungeTmpdir(tmpdir())
}

// A folder is ephemeral if its name IS the prefix (cwd == exact tmpdir, a
// rare case) or HANGS OFF it: cwd == tmpdir + "/something...", which munges
// to prefix + "-something...". The '-' separator after the prefix is what
// avoids false positives with a real project whose name happens to start
// the same way — e.g. cwd "/tmporary/project" munges to
// "-tmporary-project", which starts with "-tmp" but NOT with "-tmp-" (the
// character right after the prefix is 'o', not '-'), so it doesn't hang off
// /tmp and isn't hidden.
export function isEphemeralFolder(folderName: string, prefix: string): boolean {
  return folderName === prefix || folderName.startsWith(prefix + '-')
}

// SILOS_NO_EPHEMERAL=1 turns this rule off at startup — null instead of the prefix,
// which SessionIndex/watcher already accept as "no rule" (their long-standing
// default). This exists EXCLUSIVELY for test harnesses that legitimately
// seed fixture projects under the OS tmpdir (web/e2e/helpers.ts creates its
// folders with mkdtempSync inside os.tmpdir()) — without this escape hatch,
// the rule itself would treat those fixtures as internal noise and hide
// them, and the E2E harness would never see its sessions. This is NOT an
// owner-facing setting: it doesn't appear in any product flow, only
// index.ts reads it at startup (same pattern as the rest of the
// SILOS_* overrides in config.ts).
export function resolveEphemeralPrefix(): string | null {
  if (process.env.SILOS_NO_EPHEMERAL === '1') return null
  return ephemeralPrefix()
}
